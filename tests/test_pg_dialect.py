"""Traduction SQLite -> PostgreSQL (database/pg_dialect.py).

Chaque cas est une différence mesurée entre les deux moteurs ; les données entre
apostrophes ne doivent jamais être modifiées.
"""
from __future__ import annotations

import os

os.environ.setdefault("DISCORD_TOKEN", "ci.fake.token")

from database import pg_dialect as d  # noqa: E402
from database.pg_dialect import TableInfo  # noqa: E402

CATALOG = {
    "economy": TableInfo(columns=["guild_id", "user_id", "cash", "bank", "rowid"], primary_key=["guild_id", "user_id"]),
    "counters": TableInfo(columns=["k", "hits", "rowid"], primary_key=["k"]),
}


def tr(sql: str) -> str:
    return d.translate(sql, CATALOG.get).sql


def test_parametres_numerotes_sans_toucher_aux_chaines():
    assert tr("SELECT * FROM t WHERE a = ? AND b = '?' AND c = ?") == \
        "SELECT * FROM t WHERE a = $1 AND b = '?' AND c = $2"


def test_insert_or_ignore_devient_on_conflict_do_nothing_et_rend_le_rowid():
    sql = tr("INSERT OR IGNORE INTO economy (guild_id, user_id) VALUES (?, ?)")
    assert sql == "INSERT INTO economy (guild_id, user_id) VALUES ($1, $2) ON CONFLICT DO NOTHING RETURNING rowid"


def test_insert_or_replace_devient_un_upsert_sur_la_cle_primaire():
    sql = tr("INSERT OR REPLACE INTO economy (guild_id, user_id, cash) VALUES (?, ?, ?)")
    assert "ON CONFLICT (guild_id, user_id) DO UPDATE SET cash = excluded.cash" in sql
    assert sql.startswith("INSERT INTO economy")


def test_do_update_qualifie_les_colonnes_que_postgres_juge_ambigues():
    sql = tr("INSERT INTO counters (k, hits) VALUES (?, 1) ON CONFLICT(k) DO UPDATE SET hits = hits + excluded.hits")
    assert "SET hits = counters.hits + excluded.hits" in sql


def test_heure_unix_like_insensible_a_la_casse_et_max_scalaire():
    sql = tr("UPDATE t SET at = strftime('%s','now'), n = MAX(n - 1, 0) WHERE name LIKE ? AND x NOT LIKE ?")
    assert "(EXTRACT(EPOCH FROM now())::BIGINT)" in sql
    assert "GREATEST(n - 1, 0)" in sql
    assert "name ILIKE $1" in sql and "x NOT ILIKE $2" in sql
    assert tr("SELECT MAX(score) FROM t") == "SELECT MAX(score) FROM t"


def test_create_table_types_identite_rowid_et_nom_de_colonne_intact():
    sql = tr(
        "-- commentaire\nCREATE TABLE IF NOT EXISTS logs (\n"
        "  id INTEGER PRIMARY KEY AUTOINCREMENT,\n  timestamp INTEGER,\n  done BOOLEAN DEFAULT 0,\n"
        "  ratio REAL, data BLOB, at INTEGER DEFAULT (strftime('%s','now'))\n)"
    )
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in sql
    assert "timestamp BIGINT" in sql, "une colonne nommée timestamp garde son nom"
    assert "done BIGINT DEFAULT 0" in sql
    assert "ratio DOUBLE PRECISION" in sql and "data BYTEA" in sql
    assert "rowid BIGINT GENERATED ALWAYS AS (id) STORED" in sql
    assert "EXTRACT(EPOCH FROM now())" in sql
    assert "commentaire" not in sql


def test_table_sans_cle_entiere_recoit_un_rowid_identite():
    sql = tr("CREATE TABLE IF NOT EXISTS kv (key TEXT PRIMARY KEY, value TEXT)")
    assert "rowid BIGINT GENERATED BY DEFAULT AS IDENTITY" in sql


def test_alter_table_ne_change_que_le_type():
    assert tr("ALTER TABLE levels ADD COLUMN timestamp INTEGER DEFAULT 0") == \
        "ALTER TABLE levels ADD COLUMN timestamp BIGINT DEFAULT 0"


def test_script_decoupe_sur_les_points_virgules_hors_chaines():
    script = "CREATE TABLE a (x TEXT DEFAULT ';'); INSERT INTO a VALUES ('b;c');\n-- fin ;\n"
    assert d.split_statements(script) == ["CREATE TABLE a (x TEXT DEFAULT ';')", "INSERT INTO a VALUES ('b;c')"]


def test_pragma_et_transactions_sont_reconnus():
    assert d.translate("PRAGMA table_info(levels)").kind == "pragma"
    assert d.translate("BEGIN IMMEDIATE").kind == "tx"
    assert d.translate("VACUUM").kind == "noop"


def test_somme_de_comparaisons_devient_un_case():
    sql = tr("SELECT SUM(vote = 1) AS up, SUM(vote = -1) AS down, SUM(amount) AS total FROM v WHERE s = ?")
    assert "SUM(CASE WHEN (vote = 1) THEN 1 ELSE 0 END)" in sql
    assert "SUM(CASE WHEN (vote = -1) THEN 1 ELSE 0 END)" in sql
    assert "SUM(amount)" in sql
